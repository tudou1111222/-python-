# 外层循环：控制九九乘法表的总行数，一共9行
# 变量i代表当前是第几行，同时作为乘法算式的第一个乘数
# range(1,10) 遵循左闭右开规则，生成 1、2、3...9 的整数序列
for i in range(1, 10):
    # 内层循环：控制当前行要输出多少个乘法算式
    # 第i行有i个算式，j从1开始一直到i结束
    # 因为range不包含结束值，所以写i+1才能让j取到i
    for j in range(1, i + 1):
        # 按格式输出单个乘法算式
        # f"{i}*{j}={i*j}" 自动拼接算式和计算结果
        # end="\t" 表示输出后追加制表符，取消print默认的自动换行，让多个算式排在同一行
        print(f"{i}*{j}={i*j}", end="\t")
    # 内层循环跑完（当前行所有算式都打印完毕），执行空打印实现换行
    print()